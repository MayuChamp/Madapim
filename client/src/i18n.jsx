export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem('app_lang') || 'he'; } catch { return 'he'; }
  });

  const setLang = (newLang) => {
    setLangState(newLang);
    try { localStorage.setItem('app_lang', newLang); } catch {}
  };

  // Apply dir/lang to <html> whenever language changes
  useEffect(() => {
    const isRTL = RTL_LANGS.has(lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
  }, [lang]);

  const t = (key, vars) => {
    const dict = translations[lang] || translations.he;
    const str = dict[key] ?? translations.he[key] ?? key;
    return interpolate(str, vars);
  };

  const isRTL = RTL_LANGS.has(lang);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, isRTL }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}
