function levelFromScore(score) {
  const n = Number(score);
  if (!Number.isFinite(n)) return null;
  return (PERFORMANCE_LEVELS.find(l => n >= l.min) || PERFORMANCE_LEVELS[PERFORMANCE_LEVELS.length - 1]).key;
}

function levelLabel(key) {
  const l = PERFORMANCE_LEVELS.find(x => x.key === key);
  return l ? l.label : (key || '—');
}

// Σ(score × weight) / Σ(weight). With the main rubric's weights (25/15/30/30)
// this is exactly C1×0.25 + C2×0.15 + C3×0.30 + C4×0.30.
function weightedScore(categories) {
  const scored = (categories || []).filter(c => Number.isFinite(Number(c.score)) && c.score !== null && c.score !== '' && Number(c.weight) > 0);
  const totalWeight = scored.reduce((a, c) => a + Number(c.weight), 0);
  if (totalWeight === 0) return null;
  const sum = scored.reduce((a, c) => a + Number(c.score) * Number(c.weight), 0);
  return Math.round(sum / totalWeight);
}

function isMainRubric(rubric) {
  return rubric?.id === MAIN_RUBRIC_ID;
}

// Adds the rubric-level material that has no DB column (scale + protocol).
function decorateRubric(rubric) {
  if (!rubric) return rubric;
  if (!isMainRubric(rubric)) return rubric;
  return { ...rubric, is_main: true, level_scale: PERFORMANCE_LEVELS, protocol: EVALUATION_PROTOCOL };
}

